import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

function sanitizeIdent(raw) {
  return raw.replace(/^[@%]/, "v_").replace(/[^a-zA-Z0-9_]/g, "_");
}

function mapIrType(irType) {
  const t = irType.trim();
  if (t === "i1") return "bool";
  if (t === "i8") return "uint8_t";
  if (t === "i16") return "uint16_t";
  if (t === "i32") return "uint32_t";
  if (t === "i64") return "uint64_t";
  if (t === "i128") return "__uint128_t";
  if (t === "float") return "float";
  if (t === "double") return "double";
  if (t === "ptr" || t.endsWith("*")) return "uint8_t*";
  if (t === "void") return "void";
  return "uint64_t";
}

function mapSignedIrType(irType) {
  const t = irType.trim();
  if (t === "i8") return "int8_t";
  if (t === "i16") return "int16_t";
  if (t === "i32") return "int32_t";
  if (t === "i64") return "int64_t";
  if (t === "i128") return "__int128_t";
  return mapIrType(t);
}

function formatOperand(op, irType = "i64") {
  const trimmed = op.trim();
  if (trimmed.startsWith("%") || trimmed.startsWith("@")) return sanitizeIdent(trimmed);
  if (trimmed === "true") return "true";
  if (trimmed === "false") return "false";
  if (trimmed === "null" || trimmed === "zeroinitializer" || trimmed === "undef" || trimmed === "poison") {
    return irType === "ptr" ? "nullptr" : "0";
  }
  if (/^-?\d+$/.test(trimmed)) {
    if (irType === "i64") return `${trimmed}ULL`;
    if (irType === "i32") return `${trimmed}U`;
    return trimmed;
  }
  return trimmed;
}

/**
 * Decompiles PPU LLVM IR functions (`@__0x...`) emitted by RPCS3's PPUTranslator
 * into standalone C++20 source with inline guest page-table memory access and
 * direct HLE/runtime library calls.
 */
export function decompilePpuIrToCpp(irText, options = {}) {
  const inlineMemory = options.inlineMemory !== false;
  const functions = [];
  const fnRegex = /define\s+[^@]*@(__0x[0-9a-fA-F]+)\s*\(([^)]*)\)[^{]*\{([\s\S]*?)^\}/gm;
  let match;
  while ((match = fnRegex.exec(irText)) !== null) {
    const name = match[1];
    const body = match[3];
    functions.push(parseFunction(name, body));
  }

  const lines = [
    "// Auto-generated by web/scripts/decompile-ppu-to-cpp.mjs",
    "// Permanent PPU -> C++ -> Wasm recompilation unit",
    "#include <cstdint>",
    "#include <cstring>",
    "#include <cmath>",
    "#include <bit>",
    "",
    "extern \"C\" {",
    "  extern uint8_t* __rpcs3_guest_pages[1048576];",
    "  extern uint32_t __rpcs3_web_page_versions[1048576];",
    "  void __check(void* thread, uint64_t cia);",
    "  void __error(void* thread, uint64_t cia, uint32_t op);",
    "  void __syscall(void* thread, uint64_t code);",
    "  void __lv1call(void* thread, uint64_t code);",
    "  uint64_t __get_tb();",
    "  uint32_t __lwarx(void* thread, uint64_t addr);",
    "  uint64_t __ldarx(void* thread, uint64_t addr);",
    "  uint32_t __stwcx(void* thread, uint64_t addr, uint32_t value);",
    "  uint32_t __stdcx(void* thread, uint64_t addr, uint64_t value);",
    "  uint8_t rpcs3_web_vm_read8_raw(uint32_t addr);",
    "  uint16_t rpcs3_web_vm_read16_raw(uint32_t addr);",
    "  uint32_t rpcs3_web_vm_read32_raw(uint32_t addr);",
    "  uint64_t rpcs3_web_vm_read64_raw(uint32_t addr);",
    "  void rpcs3_web_vm_write8_raw(uint32_t addr, uint8_t value);",
    "  void rpcs3_web_vm_write16_raw(uint32_t addr, uint16_t value);",
    "  void rpcs3_web_vm_write32_raw(uint32_t addr, uint32_t value);",
    "  void rpcs3_web_vm_write64_raw(uint32_t addr, uint64_t value);",
    "}",
    "",
    "namespace rpcs3_decompiled {",
  ];

  if (inlineMemory) {
    lines.push(
      "  template <typename T, typename RawFn>",
      "  static inline T vm_read_fast(uint32_t addr, RawFn fallback) noexcept {",
      "    const uint32_t page = addr >> 12;",
      "    const uint32_t offset = addr & 0xfffu;",
      "    uint8_t* const base = __rpcs3_guest_pages[page];",
      "    if (base && offset <= 4096u - sizeof(T)) {",
      "      T value;",
      "      std::memcpy(&value, base + offset, sizeof(T));",
      "      return value;",
      "    }",
      "    return fallback(addr);",
      "  }",
      "",
      "  template <typename T, typename RawFn>",
      "  static inline void vm_write_fast(uint32_t addr, T value, RawFn fallback) noexcept {",
      "    const uint32_t page = addr >> 12;",
      "    const uint32_t offset = addr & 0xfffu;",
      "    uint8_t* const base = __rpcs3_guest_pages[page];",
      "    if (base && offset <= 4096u - sizeof(T)) {",
      "      std::memcpy(base + offset, &value, sizeof(T));",
      "      __atomic_fetch_add(&__rpcs3_web_page_versions[page], 1u, __ATOMIC_RELAXED);",
      "      return;",
      "    }",
      "    fallback(addr, value);",
      "  }",
    );
  }

  lines.push("} // namespace rpcs3_decompiled", "");

  for (const fn of functions) {
    lines.push(`extern "C" void ${fn.name}(uint8_t* v_0, uint8_t* v_1, uint64_t v_2, uint8_t* v_3, uint64_t v_4, uint64_t v_5, uint64_t v_6);`);
  }
  lines.push("");

  for (const fn of functions) {
    lines.push(...emitCppFunction(fn, inlineMemory), "");
  }

  // Emit block address metadata table for AOT registration
  const sortedAddrs = functions
    .map((fn) => ({ name: fn.name, addr: Number.parseInt(fn.name.slice(2), 16) >>> 0 }))
    .sort((a, b) => a.addr - b.addr);
  lines.push(
    "extern \"C\" {",
    `  extern const uint32_t __ppu_decompiled_count = ${sortedAddrs.length}u;`,
    `  extern const uint32_t __ppu_decompiled_addrs[${Math.max(1, sortedAddrs.length)}] = {`,
    `    ${sortedAddrs.map((item) => `0x${item.addr.toString(16)}u`).join(", ") || "0u"}`,
    "  };",
    "}",
  );

  return {
    cpp: lines.join("\n"),
    functionCount: functions.length,
    functions: functions.map((fn) => fn.name),
  };
}

function parseFunction(name, bodyText) {
  const blocks = [];
  let currentBlock = { label: "entry", phis: [], instructions: [] };
  blocks.push(currentBlock);

  for (const rawLine of bodyText.split(/\r?\n/)) {
    const line = rawLine.replace(/;.*$/, "").trim();
    if (!line) continue;
    const labelMatch = /^([a-zA-Z0-9_$.]+):$/.exec(line);
    if (labelMatch) {
      currentBlock = { label: sanitizeIdent(`%${labelMatch[1]}`), phis: [], instructions: [] };
      blocks.push(currentBlock);
      continue;
    }
    const phiMatch = /^(%[a-zA-Z0-9_$.]+)\s*=\s*phi\s+([^\s]+)\s+(.+)$/.exec(line);
    if (phiMatch) {
      const pairs = [];
      const pairRe = /\[\s*([^,]+?)\s*,\s*(%[a-zA-Z0-9_$.]+)\s*\]/g;
      let pm;
      while ((pm = pairRe.exec(phiMatch[3])) !== null) {
        pairs.push({ value: pm[1].trim(), pred: sanitizeIdent(pm[2].trim()) });
      }
      currentBlock.phis.push({
        dest: sanitizeIdent(phiMatch[1]),
        type: phiMatch[2],
        pairs,
      });
      continue;
    }
    currentBlock.instructions.push(line);
  }
  return { name, blocks: blocks.filter((b) => b.instructions.length > 0 || b.phis.length > 0) };
}

function emitCppFunction(fn, inlineMemory) {
  const decls = new Map();
  const phiIncoming = new Map(); // `${predLabel}->${targetLabel}` -> [{ dest, expr, type }]

  for (const block of fn.blocks) {
    for (const phi of block.phis) {
      decls.set(phi.dest, mapIrType(phi.type));
      for (const pair of phi.pairs) {
        const key = `${pair.pred}->${block.label}`;
        const list = phiIncoming.get(key) ?? [];
        list.push({ dest: phi.dest, expr: formatOperand(pair.value, phi.type), type: mapIrType(phi.type) });
        phiIncoming.set(key, list);
      }
    }
  }

  const bodyLines = [];
  for (const block of fn.blocks) {
    bodyLines.push(`  ${block.label}:;`);
    for (const inst of block.instructions) {
      const translated = translateInstruction(inst, block.label, decls, phiIncoming, inlineMemory);
      for (const line of translated) bodyLines.push(`    ${line}`);
    }
  }

  const header = [
    `extern "C" void ${fn.name}(uint8_t* v_0, uint8_t* v_1, uint64_t v_2, uint8_t* v_3, uint64_t v_4, uint64_t v_5, uint64_t v_6) {`,
  ];
  for (const [varName, cppType] of decls.entries()) {
    header.push(`  ${cppType} ${varName}{};`);
  }
  return [...header, ...bodyLines, "}"];
}

function emitEdgeAssignments(fromLabel, toLabel, phiIncoming) {
  const moves = phiIncoming.get(`${fromLabel}->${toLabel}`);
  if (!moves || moves.length === 0) return `goto ${toLabel};`;
  const temps = moves.map((m, idx) => `${m.type} _phi_${idx} = ${m.expr};`).join(" ");
  const commits = moves.map((m, idx) => `${m.dest} = _phi_${idx};`).join(" ");
  return `{ ${temps} ${commits} goto ${toLabel}; }`;
}

function translateInstruction(inst, currentLabel, decls, phiIncoming, inlineMemory) {
  if (inst === "ret void" || inst.startsWith("ret ")) {
    return ["return;"];
  }
  if (inst === "unreachable") {
    return ["__builtin_unreachable();"];
  }
  const brUncond = /^br\s+label\s+(%[a-zA-Z0-9_$.]+)$/.exec(inst);
  if (brUncond) {
    const target = sanitizeIdent(brUncond[1]);
    return [emitEdgeAssignments(currentLabel, target, phiIncoming)];
  }
  const brCond = /^br\s+i1\s+([^,]+),\s*label\s+(%[a-zA-Z0-9_$.]+),\s*label\s+(%[a-zA-Z0-9_$.]+)$/.exec(inst);
  if (brCond) {
    const cond = formatOperand(brCond[1], "i1");
    const tLabel = sanitizeIdent(brCond[2]);
    const fLabel = sanitizeIdent(brCond[3]);
    return [
      `if (${cond}) ${emitEdgeAssignments(currentLabel, tLabel, phiIncoming)}`,
      `else ${emitEdgeAssignments(currentLabel, fLabel, phiIncoming)}`,
    ];
  }

  const storeMatch = /^store\s+(?:volatile\s+)?([^\s]+)\s+([^,]+),\s*ptr\s+([^,]+)(?:,\s*align\s+\d+)?$/.exec(inst);
  if (storeMatch) {
    const valType = storeMatch[1];
    const cppType = mapIrType(valType);
    const val = formatOperand(storeMatch[2], valType);
    const ptr = formatOperand(storeMatch[3], "ptr");
    return [`{ const ${cppType} _st = ${val}; std::memcpy(${ptr}, &_st, sizeof(_st)); }`];
  }

  const voidCallMatch = /^(?:tail\s+|musttail\s+)?call\s+(?:[a-z_]+\s+)*void\s+@([a-zA-Z0-9_$.]+)\((.*)\)$/.exec(inst);
  if (voidCallMatch) {
    const callee = voidCallMatch[1];
    const args = splitCallArgs(voidCallMatch[2]);
    const writeRaw = /^rpcs3_web_vm_write(8|16|32|64)_raw$/.exec(callee);
    if (writeRaw && inlineMemory && args.length === 2) {
      const bits = Number(writeRaw[1]);
      return [`rpcs3_decompiled::vm_write_fast<uint${bits}_t>(${args[0].expr}, ${args[1].expr}, rpcs3_web_vm_write${bits}_raw);`];
    }
    return [`${callee}(${args.map((a) => a.expr).join(", ")});`];
  }

  const assignMatch = /^(%[a-zA-Z0-9_$.]+)\s*=\s*(.+)$/.exec(inst);
  if (!assignMatch) {
    return [`/* unhandled: ${inst} */`];
  }
  const dest = sanitizeIdent(assignMatch[1]);
  const rhs = assignMatch[2].trim();

  const loadMatch = /^load\s+(?:volatile\s+)?([^\s,]+),\s*ptr\s+([^,]+)(?:,\s*align\s+\d+)?$/.exec(rhs);
  if (loadMatch) {
    const valType = loadMatch[1];
    const cppType = mapIrType(valType);
    const ptr = formatOperand(loadMatch[2], "ptr");
    decls.set(dest, cppType);
    return [`std::memcpy(&${dest}, ${ptr}, sizeof(${cppType}));`];
  }

  const gepMatch = /^getelementptr\s+(?:inbounds\s+)?i8,\s*ptr\s+([^,]+),\s*(i\d+)\s+(.+)$/.exec(rhs);
  if (gepMatch) {
    const base = formatOperand(gepMatch[1], "ptr");
    const offset = formatOperand(gepMatch[3], gepMatch[2]);
    decls.set(dest, "uint8_t*");
    return [`${dest} = ${base} + ${offset};`];
  }

  const binMatch = /^(add|sub|mul|and|or|xor|shl|lshr|ashr|udiv|sdiv|urem|srem|fadd|fsub|fmul|fdiv)\s+(?:nsw\s+|nuw\s+|exact\s+)*([^\s]+)\s+([^,]+),\s*(.+)$/.exec(rhs);
  if (binMatch) {
    const [, op, ty, lhsRaw, rhsRaw] = binMatch;
    const cppType = mapIrType(ty);
    const signedType = mapSignedIrType(ty);
    const a = formatOperand(lhsRaw, ty);
    const b = formatOperand(rhsRaw, ty);
    decls.set(dest, cppType);
    const opMap = {
      add: "+", sub: "-", mul: "*", and: "&", or: "|", xor: "^",
      shl: "<<", lshr: ">>", udiv: "/", urem: "%",
      fadd: "+", fsub: "-", fmul: "*", fdiv: "/",
    };
    if (op in opMap) {
      return [`${dest} = static_cast<${cppType}>(${a} ${opMap[op]} ${b});`];
    }
    if (op === "ashr" || op === "sdiv" || op === "srem") {
      const sym = op === "ashr" ? ">>" : op === "sdiv" ? "/" : "%";
      return [`${dest} = static_cast<${cppType}>(static_cast<${signedType}>(${a}) ${sym} static_cast<${signedType}>(${b}));`];
    }
  }

  const icmpMatch = /^icmp\s+(eq|ne|ugt|uge|ult|ule|sgt|sge|slt|sle)\s+([^\s]+)\s+([^,]+),\s*(.+)$/.exec(rhs);
  if (icmpMatch) {
    const [, pred, ty, lhsRaw, rhsRaw] = icmpMatch;
    const a = formatOperand(lhsRaw, ty);
    const b = formatOperand(rhsRaw, ty);
    const signedType = mapSignedIrType(ty);
    decls.set(dest, "bool");
    const unsignedMap = { eq: "==", ne: "!=", ugt: ">", uge: ">=", ult: "<", ule: "<=" };
    if (pred in unsignedMap) {
      return [`${dest} = (${a} ${unsignedMap[pred]} ${b});`];
    }
    const signedMap = { sgt: ">", sge: ">=", slt: "<", sle: "<=" };
    return [`${dest} = (static_cast<${signedType}>(${a}) ${signedMap[pred]} static_cast<${signedType}>(${b}));`];
  }

  const castMatch = /^(trunc|zext|sext|bitcast|sitofp|uitofp|fptosi|fptoui|fpext|fptrunc|ptrtoint|inttoptr)\s+([^\s]+)\s+([^\s]+)\s+to\s+([^\s]+)$/.exec(rhs);
  if (castMatch) {
    const [, castOp, srcTy, valRaw, dstTy] = castMatch;
    const cppDst = mapIrType(dstTy);
    const val = formatOperand(valRaw, srcTy);
    decls.set(dest, cppDst);
    if (castOp === "sext" || castOp === "sitofp") {
      return [`${dest} = static_cast<${cppDst}>(static_cast<${mapSignedIrType(srcTy)}>(${val}));`];
    }
    if (castOp === "bitcast") {
      return [`${dest} = std::bit_cast<${cppDst}>(${val});`];
    }
    if (castOp === "inttoptr" || castOp === "ptrtoint") {
      return [`${dest} = reinterpret_cast<${cppDst}>(static_cast<uintptr_t>(${val}));`];
    }
    return [`${dest} = static_cast<${cppDst}>(${val});`];
  }

  const selectMatch = /^select\s+i1\s+([^,]+),\s*([^\s]+)\s+([^,]+),\s*([^\s]+)\s+(.+)$/.exec(rhs);
  if (selectMatch) {
    const [, condRaw, ty, tRaw, , fRaw] = selectMatch;
    const cppType = mapIrType(ty);
    decls.set(dest, cppType);
    return [`${dest} = ${formatOperand(condRaw, "i1")} ? ${formatOperand(tRaw, ty)} : ${formatOperand(fRaw, ty)};`];
  }

  const callMatch = /^(?:tail\s+|musttail\s+)?call\s+(?:[a-z_]+\s+)*([^\s(]+)\s+@([a-zA-Z0-9_$.]+)\((.*)\)$/.exec(rhs);
  if (callMatch) {
    const [, retTy, callee, rawArgs] = callMatch;
    const cppType = mapIrType(retTy);
    const args = splitCallArgs(rawArgs);
    decls.set(dest, cppType);
    const readRaw = /^rpcs3_web_vm_read(8|16|32|64)_raw$/.exec(callee);
    if (readRaw && inlineMemory && args.length === 1) {
      const bits = Number(readRaw[1]);
      return [`${dest} = rpcs3_decompiled::vm_read_fast<uint${bits}_t>(${args[0].expr}, rpcs3_web_vm_read${bits}_raw);`];
    }
    if (callee.startsWith("llvm.bswap.i")) {
      const bits = Number(callee.slice("llvm.bswap.i".length));
      const builtin = bits === 16 ? "__builtin_bswap16" : bits === 32 ? "__builtin_bswap32" : "__builtin_bswap64";
      return [`${dest} = ${builtin}(${args[0].expr});`];
    }
    if (callee.startsWith("llvm.ctlz.i")) {
      const bits = Number(callee.slice("llvm.ctlz.i".length));
      return [`${dest} = ${args[0].expr} ? static_cast<${cppType}>(${bits === 64 ? "__builtin_clzll" : "__builtin_clz"}(${args[0].expr})) : ${bits}u;`];
    }
    return [`${dest} = ${callee}(${args.map((a) => a.expr).join(", ")});`];
  }

  return [`/* unhandled: ${inst} */`];
}

function splitCallArgs(rawArgs) {
  const trimmed = rawArgs.trim();
  if (!trimmed) return [];
  return trimmed.split(",").map((part) => {
    const tokens = part.trim().split(/\s+/);
    const type = tokens[0];
    const value = tokens[tokens.length - 1];
    return { type, expr: formatOperand(value, type) };
  });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const input = args.find((a) => a.endsWith(".ll"));
  const output = args.find((a) => a.endsWith(".cpp"));
  const wasmOption = args.find((a) => a.startsWith("--compile-wasm="));
  if (!input || !output) {
    throw new Error("usage: decompile-ppu-to-cpp.mjs INPUT.ll OUTPUT.cpp [--compile-wasm=OUT.wasm]");
  }
  const irText = readFileSync(resolve(input), "utf8");
  const result = decompilePpuIrToCpp(irText);
  writeFileSync(resolve(output), result.cpp, "utf8");
  console.log(`Decompiled ${result.functionCount} PPU functions to ${output}`);
  if (wasmOption) {
    const wasmOut = resolve(wasmOption.slice("--compile-wasm=".length));
    execFileSync("em++", [
      "-O3", "-std=c++20", "-msimd128", "-pthread",
      "-sSIDE_MODULE=1",
      "-Wno-unused-label",
      resolve(output),
      "-o", wasmOut,
    ], { stdio: "inherit" });
    console.log(`Compiled C++ decompilation unit to ${wasmOut}`);
  }
}
